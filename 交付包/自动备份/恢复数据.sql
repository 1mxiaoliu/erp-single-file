-- ────────────────────────────────────────────────────────────
--  第 1 步：看看有哪些版本可以回
--  认准「数据」这一列的大小，明显变小的那一天之前通常就是正常的
-- ────────────────────────────────────────────────────────────
select saved_at as 存档时间,
       ver      as 版本,
       pg_size_pretty(pg_column_size(doc)::bigint) as 数据大小
  from public.erp_doc_history
 order by saved_at desc
 limit 40;


-- ────────────────────────────────────────────────────────────
--  第 2 步：把某个时间点之前的样子取出来看一眼（不改任何东西）
--  把下面的时间改成你要的那一行
-- ────────────────────────────────────────────────────────────
