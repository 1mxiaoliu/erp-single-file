-- ────────────────────────────────────────────────────────────
--  第 3 步：确认无误，正式恢复
--  把时间改成第 1 步里挑中的那一行（照抄，别改格式）
--
--  注意：ver + 1 是必须的。这样其他设备下次打开会发现「云端比我新」，
--        会自动拉下恢复后的数据，不会拿旧数据再盖回去。
-- ────────────────────────────────────────────────────────────
update public.erp_doc
   set doc = (
         select doc from public.erp_doc_history
          where saved_at <= '2026-11-01 14:00:00+08'
          order by saved_at desc
          limit 1
       ),
       ver        = ver + 1,
       updated_at = now()
 where id = 'main';

--  跑完应该看到：UPDATE 1
--  然后所有设备重新打开网页，就是恢复后的数据了。


